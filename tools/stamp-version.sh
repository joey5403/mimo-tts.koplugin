#!/bin/sh
# Write mimo_version.lua: the plugin version, stamped at build/install time.
#
# The single source of truth is the git tag: releases use the exact tag,
# dev installs use `git describe` (e.g. 1.0.2-3-gfd552ff-dirty).
set -e
cd "$(dirname "$0")/.."
VERSION=${1:-$(git describe --tags --always --dirty 2>/dev/null || echo dev)}
VERSION=${VERSION#v}
printf -- '-- Generated by tools/stamp-version.sh (version source: git tags) --\nreturn "%s"\n' "$VERSION" > mimo_version.lua
echo "stamped mimo_version.lua: $VERSION"
